/**
 * 입력값으로 법인명 조회
 * - 대소문자, 공백 무시
 * - 매핑 히트 시 { corp_name, brand_name } 반환
 * - 미스 시 null 반환
 */
export function lookupBrandMap(input: string): { corp_name: string; brand_name: string } | null {
  const normalized = input.trim();

  // 1. 정확히 일치
  if (BRAND_TO_CORP[normalized]) {
    return { corp_name: BRAND_TO_CORP[normalized], brand_name: normalized };
  }

  // 2. 대소문자 무시 일치
  const lower = normalized.toLowerCase();
  for (const [brand, corp] of Object.entries(BRAND_TO_CORP)) {
    if (brand.toLowerCase() === lower) {
      return { corp_name: corp, brand_name: brand };
    }
  }

  return null;
}
